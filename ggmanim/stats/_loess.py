"""Local polynomial regression (loess) for one predictor, numpy only.

Reproduces R's ``loess(y ~ x, span, degree, family = "gaussian")`` (the reference
fixtures are ``tests/fixtures/loess_r.csv``, generated by ``loess_r.R``):

* **Local fit.** At a point ``x0`` the neighbourhood is the ``q = floor(n * span)``
  nearest observations; ``h`` is the distance to the ``q``-th nearest (times
  ``span`` when ``span > 1``). Observations get tricube weights
  ``(1 - (|x - x0| / h)^3)^3`` (zero beyond ``h``) and a polynomial of ``degree``
  (0, 1 or 2) in ``x - x0`` is fitted by weighted least squares; its intercept is
  the fit, its linear coefficient the slope. Both are linear in ``y``.
* **Surface.** ``surface="direct"`` evaluates the local fit at every point.
  ``surface="interpolate"`` (R's and so ggplot2's default) builds R's kd tree --
  the bounding box widened by 0.5% each side, cells split at the median
  observation until they hold at most ``floor(n * span * cell)`` points
  (``cell = 0.2``) -- fits value and slope at the cell boundaries (vertices) and
  joins them by cubic Hermite interpolation. Outside the bounding box (only with
  ``fullrange=True``), where R returns ``NaN``, the direct local fit is used.
* **Standard errors.** With ``L`` the operator mapping ``y`` to the fitted values
  at the observations, ``delta1 = tr((I-L)^T (I-L))`` and
  ``delta2 = tr(((I-L)^T (I-L))^2)``; the residual scale is
  ``s = sqrt(sum(resid^2) / delta1)``, the standard error at ``x0`` is
  ``s * ||l(x0)||`` and intervals use t quantiles with ``delta1^2 / delta2``
  degrees of freedom. The deltas are computed exactly (R's
  ``statistics = "exact"``); R's default approximates them, so its standard
  errors differ from these by well under 1%.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

__all__ = ["Loess", "loess"]

#: R's ``loess.control(cell = 0.2)``.
CELL = 0.2


def _local_rows(
    x: np.ndarray, x0: np.ndarray, q: int, span: float, degree: int
) -> tuple[np.ndarray, np.ndarray]:
    """Operator rows (``len(x0) x len(x)``) for the local fit's value and slope."""
    value = np.zeros((len(x0), len(x)))
    slope = np.zeros_like(value)
    for j, x0j in enumerate(x0):
        d = np.abs(x - x0j)
        h = float(np.partition(d, q - 1)[q - 1])
        if span > 1:
            h *= span
        if h <= 0:  # the q nearest all tie with x0: weight the ties only
            w = (d == 0).astype(float)
        else:
            w = (1.0 - np.minimum(d / h, 1.0) ** 3) ** 3
        keep = w > 0
        sw = np.sqrt(w[keep])
        X = np.vander(x[keep] - x0j, degree + 1, increasing=True)
        # the least-squares solution of (sw X) b = sw y is pinv(sw X) @ (sw y)
        P = np.linalg.pinv(sw[:, None] * X) * sw
        value[j, keep] = P[0]
        if degree >= 1:
            slope[j, keep] = P[1]
    return value, slope


def _vertices(x: np.ndarray, span: float) -> np.ndarray:
    """Sorted kd-tree vertices of R's loess (``ehg126``/``ehg124``) for 1-d ``x``."""
    xs = np.sort(x)
    n = len(xs)
    fc = int(np.floor(n * span * CELL))
    lo, hi = float(xs[0]), float(xs[-1])
    mu = 0.005 * max(hi - lo, 1e-10 * max(abs(lo), abs(hi)) + 1e-30)
    verts = [lo - mu, hi + mu]
    cells = [(0, n - 1, lo - mu, hi + mu)]  # (first, last) sorted index, bounds
    while cells:
        lo_i, hi_i, a, b = cells.pop()
        if hi_i - lo_i + 1 <= fc:
            continue
        m = (lo_i + hi_i + 2) // 2 - 1  # R's m = (l + u) / 2 with 1-based indices
        offset = 0  # move the split off a run of ties (R's 2006 fix)
        while lo_i <= m + offset < hi_i:
            if xs[m + offset] == xs[m + offset + 1]:
                offset = -offset + (1 if offset <= 0 else 0)
            else:
                m += offset
                break
        t = float(xs[m])
        if t in (a, b):
            continue
        verts.append(t)
        cells += [(lo_i, m, a, t), (m + 1, hi_i, t, b)]
    return np.array(sorted(verts))


@dataclass(frozen=True)
class Loess:
    """A fitted loess smoother (see :func:`loess`).

    Attributes
    ----------
    x, y : ndarray
        The observations.
    span, degree, surface :
        The smoothing parameters.
    q : int
        Neighbourhood size.
    vertices : ndarray or None
        kd-tree vertices (``surface="interpolate"``).
    fitted, residuals : ndarray
        Fitted values and residuals at the observations.
    s : float
        Residual standard error.
    delta1, delta2 : float
        Traces giving the residual and lookup degrees of freedom.
    enp : float
        Equivalent number of parameters, ``tr(L)``.
    """

    x: np.ndarray
    y: np.ndarray
    span: float
    degree: int
    surface: str
    q: int
    vertices: np.ndarray | None
    fitted: np.ndarray
    residuals: np.ndarray
    s: float
    delta1: float
    delta2: float
    enp: float

    @property
    def df(self) -> float:
        """Degrees of freedom for interval t quantiles, ``delta1^2 / delta2``."""
        return self.delta1**2 / self.delta2 if self.delta2 > 0 else float("inf")

    def operator(self, xnew) -> np.ndarray:
        """The rows ``l(x0)`` (``len(xnew) x n``) with ``fit(x0) = l(x0) @ y``."""
        return _operator(
            self.x, np.asarray(xnew, dtype=float), self.q, self.span, self.degree, self.vertices
        )

    def predict(self, xnew, se: bool = False):
        """Fitted values at ``xnew``; with ``se=True`` the pair ``(fit, se)``."""
        L = self.operator(np.atleast_1d(np.asarray(xnew, dtype=float)))
        fit = L @ self.y
        if not se:
            return fit
        return fit, self.s * np.sqrt(np.einsum("ij,ij->i", L, L))


def _operator(x, x0, q, span, degree, vertices) -> np.ndarray:
    if vertices is None:
        return _local_rows(x, x0, q, span, degree)[0]
    out = np.empty((len(x0), len(x)))
    inside = (x0 >= vertices[0]) & (x0 <= vertices[-1])
    if (~inside).any():
        out[~inside] = _local_rows(x, x0[~inside], q, span, degree)[0]
    if inside.any():
        z = x0[inside]
        value, slope = _local_rows(x, vertices, q, span, degree)
        i = np.clip(np.searchsorted(vertices, z, side="right") - 1, 0, len(vertices) - 2)
        h = vertices[i + 1] - vertices[i]
        u = (z - vertices[i]) / h
        # cubic Hermite basis (R's ehg128)
        b = [
            (1 - u) ** 2 * (1 + 2 * u),
            u**2 * (3 - 2 * u),
            u * (1 - u) ** 2 * h,
            -(u**2) * (1 - u) * h,
        ]
        out[inside] = (
            b[0][:, None] * value[i]
            + b[1][:, None] * value[i + 1]
            + b[2][:, None] * slope[i]
            + b[3][:, None] * slope[i + 1]
        )
    return out


def loess(x, y, span: float = 0.75, degree: int = 2, surface: str = "interpolate") -> Loess:
    """Fit ``y ~ x`` by loess (gaussian family, no robustness iterations).

    ``surface`` is ``"interpolate"`` (R's default) or ``"direct"``. Raises
    ``ValueError`` for ``degree`` outside 0..2, a non-positive ``span``, an unknown
    ``surface`` or a neighbourhood too small for the local polynomial
    (``floor(n * span) <= degree``: R's "span too small").
    """
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    degree = int(degree)
    if degree not in (0, 1, 2):
        raise ValueError(f"loess degree must be 0, 1 or 2, got {degree}")
    if not span > 0:
        raise ValueError(f"loess span must be > 0, got {span}")
    if surface not in ("interpolate", "direct"):
        raise ValueError(f"loess surface must be 'interpolate' or 'direct', got {surface!r}")
    n = len(x)
    q = min(int(np.floor(n * span + 1e-5)), n)
    if q <= degree:
        raise ValueError(
            f"loess span too small: {q} neighbour(s) for a degree-{degree} local fit "
            f"(n = {n}, span = {span})"
        )
    vertices = _vertices(x, float(span)) if surface == "interpolate" else None
    L = _operator(x, x, q, float(span), degree, vertices)
    fitted = L @ y
    resid = y - fitted
    M = np.eye(n) - L
    M = M.T @ M
    delta1 = float(np.trace(M))
    delta2 = float(np.sum(M * M.T))  # tr(M @ M)
    s = float(np.sqrt(resid @ resid / delta1)) if delta1 > 0 else float("nan")
    return Loess(
        x=x,
        y=y,
        span=float(span),
        degree=degree,
        surface=surface,
        q=q,
        vertices=vertices,
        fitted=fitted,
        residuals=resid,
        s=s,
        delta1=delta1,
        delta2=delta2,
        enp=float(np.trace(L)),
    )
