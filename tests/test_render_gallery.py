@pytest.fixture(scope="module")
def real_examples():
    return rg.discover()


# --------------------------------------------------------------------------- discovery


def test_discover_toy(examples_dir):
    (ex,) = rg.discover(examples_dir)  # helpers.py has no scene and is dropped
    assert ex.module == "toy"
    assert ex.summary == "Toy example."
    assert [s.name for s in ex.scenes] == ["Still", "Moving"]  # _Base, NotAScene skipped
    still, moving = ex.scenes
    assert still.doc == "A still scene."
    assert (still.animated, moving.animated) == (False, True)
    assert still.image == "img/toy/Still.png"
    assert moving.image == "img/toy/Moving.gif"
    assert still.anchor == "toy-still"


def test_scene_source_follows_helpers_transitively(examples_dir):
    still = rg.discover(examples_dir)[0].scenes[0]
    src = still.source
    for needed in ("N = 10", "def data():", "def make_plot():", "class _Base(Scene):"):
        assert needed in src
    assert "UNUSED" not in src
    assert "import" not in src
    assert "class Moving" not in src
    # source order is kept, and the scene class comes last
    order = [src.index(s) for s in ("N = 10", "def data", "def make_plot", "class _Base")]
    assert order == sorted(order)
    assert src.rstrip().endswith('"""A still scene."""')


def test_moving_source_is_just_the_class(examples_dir):
    moving = rg.discover(examples_dir)[0].scenes[1]
    assert moving.source.startswith("class Moving(Scene):")
    assert "def data" not in moving.source


def _imported_scenes(path: Path) -> set[str]:
    """Scene classes manim's ``-a`` would find: defined in the module itself."""
    sys.path.insert(0, str(path.parent))
    try:
        mod = importlib.import_module(path.stem)
    finally:
        sys.path.remove(str(path.parent))
    return {
        name
        for name, obj in vars(mod).items()
        if inspect.isclass(obj)
        and issubclass(obj, Scene)
        and obj.__module__ == mod.__name__
        and not name.startswith("_")
    }


def test_discovery_matches_import(real_examples):
    examples = sorted(rg.EXAMPLES.glob("*.py"))
    assert len(examples) >= 20
    found = {ex.module: {s.name for s in ex.scenes} for ex in real_examples}
    for path in examples:
        assert found.get(path.stem, set()) == _imported_scenes(path), path.name


def test_animated_marker(real_examples):
    animated = {s.key for ex in real_examples for s in ex.scenes if s.animated}
    assert {"transitions.StatesLoop", "polar.BarsToPie", "live_plot.SineTracker"} <= animated
    assert "polar.Polar" not in animated
    for ex in real_examples:
        for s in ex.scenes:
            assert rg.MARKER not in s.source  # the marker is not shown in the gallery
    loop = next(s for ex in real_examples for s in ex.scenes if s.key == "transitions.StatesLoop")
    assert loop.animated and loop.image.endswith(".gif")


# --------------------------------------------------------------------------- page


def test_render_index_toy(examples_dir):
    page = rg.render_index(rg.discover(examples_dir))
    assert page.startswith("<!-- Generated by scripts/render_gallery.py")
    assert "2 scenes from 1 files" in page
    assert "## toy.py { #toy }" in page
    assert "### Still { #toy-still }" in page
    assert "![toy.Still](img/toy/Still.png){ loading=lazy }" in page
    assert '](#toy-moving "toy.Moving")' in page  # thumbnail link
    assert '???+ example "`manim -ql -s examples/toy.py Still`"' in page
    assert f"--format gif --fps {rg.GIF_FPS} examples/toy.py Moving" in page
    # the source sits inside the admonition: every line indented (or blank)
    block = page.split('examples/toy.py Still`"\n\n', 1)[1].split("\n\n</div>", 1)[0]
    assert page.count('<div class="gallery-scene" markdown>') == 2
    assert block.startswith("    ```python\n    N = 10")
    assert all(not line or line.startswith("    ") for line in block.splitlines())


def test_render_index_real(real_examples):
    page = rg.render_index(real_examples)
    scenes = [s for ex in real_examples for s in ex.scenes]
    anchors = [s.anchor for s in scenes] + [ex.module.replace("_", "-") for ex in real_examples]
    assert len(set(anchors)) == len(anchors)
    for s in scenes:
        assert f"{{ #{s.anchor} }}" in page
        assert f"({s.image})" in page
    assert page == rg.render_index(rg.discover())  # deterministic


