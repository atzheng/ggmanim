def test_manim_args(examples_dir, tmp_path):
    still, moving = rg.discover(examples_dir)[0].scenes
    args = rg.manim_args(still, tmp_path / "m")
    assert args[:2] == ["-ql", "-s"]
    assert args[-2:] == [str(still.path), "Still"]
    gif = rg.manim_args(moving, tmp_path / "m")
    assert gif[:5] == ["-ql", "--format", "gif", "--fps", str(rg.GIF_FPS)]


FAKE_MANIM = (
    "import sys, pathlib\n"
    "a = sys.argv[1:]\n"
    "media = pathlib.Path(a[a.index('--media_dir') + 1])\n"
    "ext = 'gif' if 'gif' in a else 'png'\n"
    "out = media / 'x' / ('%s_ManimCE_v0.png' % a[-1]).replace('png', ext)\n"
    "out.parent.mkdir(parents=True)\n"
    "out.write_bytes(b'img')\n"
    "(media / 'partial_movie_files').mkdir()\n"
    "(media / 'partial_movie_files' / out.name).write_bytes(b'partial')\n"
)


def test_render_scene_copies_output(examples_dir, tmp_path):
    img = tmp_path / "img"
    manim = [sys.executable, "-c", FAKE_MANIM]
    results = rg.render_all(rg.discover(examples_dir)[0].scenes, manim, jobs=2, img_dir=img)
    assert all(r.ok for r in results), [r.log for r in results]
    assert (img / "toy" / "Still.png").read_bytes() == b"img"
    assert (img / "toy" / "Moving.gif").read_bytes() == b"img"


def test_render_scene_failure(examples_dir, tmp_path):
    still = rg.discover(examples_dir)[0].scenes[0]
    img = tmp_path / "img"
    res = rg.render_scene(still, [sys.executable, "-c", "import sys; sys.exit(3)"], img)
    assert not res.ok
    assert not img.exists()
